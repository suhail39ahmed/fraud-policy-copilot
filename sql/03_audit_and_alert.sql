-- Serverless Alert: fires when any high-risk review exists in last hour
-- Requires ACCOUNTADMIN. If Alert unsupported on trial, keep the VIEW + Task fallback below.
CREATE OR REPLACE ALERT FRAUD_HIGH_RISK_ALERT
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = '60 MINUTE'
  IF (EXISTS (
    SELECT 1 FROM REVIEW_AUDIT
    WHERE RISK_SCORE >= 70
      AND REVIEWED_AT >= DATEADD('hour', -1, CURRENT_TIMESTAMP())
  ))
  THEN
    INSERT INTO CASE_EVENTS (CASE_ID, TXN_ID, EVENT_TYPE, EVENT_DATA, ACTOR)
    SELECT
      NULL,
      a.TXN_ID,
      'ALERT_HIGH_RISK',
      OBJECT_CONSTRUCT(
        'risk_score', a.RISK_SCORE,
        'recommendation', a.RECOMMENDATION,
        'reviewed_at', a.REVIEWED_AT
      ),
      'FRAUD_HIGH_RISK_ALERT'
    FROM REVIEW_AUDIT a
    WHERE a.RISK_SCORE >= 70
      AND a.REVIEWED_AT >= DATEADD('hour', -1, CURRENT_TIMESTAMP());

ALTER ALERT FRAUD_HIGH_RISK_ALERT RESUME;

