-- Phase 1b: per-run audit log + Snowflake Alert on high-risk reviews
USE DATABASE FRAUD_COPILOT;
USE SCHEMA DEMO;

CREATE TABLE IF NOT EXISTS REVIEW_AUDIT (
  AUDIT_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
  TXN_ID STRING NOT NULL,
  RISK_SCORE NUMBER(5,2),
  RECOMMENDATION STRING,
  FIRED_RULES VARIANT,
  SOURCE STRING DEFAULT 'STREAMLIT',
  REVIEWED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  REVIEWED_BY STRING DEFAULT CURRENT_USER()
);

-- View: latest high-risk reviews in the last 24h (alert condition source)
CREATE OR REPLACE VIEW HIGH_RISK_REVIEWS_24H AS
SELECT *
FROM REVIEW_AUDIT
WHERE RISK_SCORE >= 70
  AND REVIEWED_AT >= DATEADD('hour', -24, CURRENT_TIMESTAMP());

